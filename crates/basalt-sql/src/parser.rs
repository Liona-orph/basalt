/// Maximum nesting depth of parenthesised expressions, subqueries and join
/// trees.
///
/// Chosen so that the deepest realistic hand-written query is nowhere near it
/// while the parser still cannot be made to overflow its stack: each level costs
/// a few hundred bytes of stack across the mutually recursive functions, so 96
/// levels is well under 100 KiB even in a debug build.
pub const MAX_RECURSION_DEPTH: usize = 96;

/// Result alias for the parser.
pub type ParseResult<T> = Result<T, SqlError>;

/// Returned by [`Parser::token`] in the unreachable case where the cursor has
/// somehow left the token vector, so that the accessor is total.
static EOF_TOKEN: Token = Token::new(TokenKind::Eof, Span::at(0));

/// Parse exactly one statement, which may be followed by a single `;`.
///
/// ```
/// use basalt_sql::parse;
///
/// let statement = parse("SELECT a, count(*) FROM t GROUP BY a HAVING count(*) > 2")?;
/// assert_eq!(
///     statement.to_string(),
///     "SELECT a, count(*) FROM t GROUP BY a HAVING count(*) > 2",
/// );
/// # Ok::<(), basalt_sql::SqlError>(())
/// ```
pub fn parse(sql: &str) -> ParseResult<Statement> {
    let mut parser = Parser::new(sql)?;
    let statement = parser.parse_statement()?;
    parser.eat_symbol(Symbol::Semicolon);
    if !parser.at_eof() {
        return Err(parser
            .error_expected(&["end of statement"])
            .with_hint("separate statements with `;` and parse them with `parse_many`"));
    }
    Ok(statement)
}

/// Parse a `;`-separated script.
///
/// Empty statements (`;;`) are skipped rather than rejected, because scripts
/// generated by other tools routinely contain them.
///
/// ```
/// use basalt_sql::parse_many;
///
/// let statements = parse_many("SELECT 1; SELECT 2;")?;
/// assert_eq!(statements.len(), 2);
/// # Ok::<(), basalt_sql::SqlError>(())
/// ```
pub fn parse_many(sql: &str) -> ParseResult<Vec<Statement>> {
    let mut parser = Parser::new(sql)?;
    let mut statements = Vec::new();
    loop {
        while parser.eat_symbol(Symbol::Semicolon) {}
        if parser.at_eof() {
            return Ok(statements);
        }
        statements.push(parser.parse_statement()?);
        if !parser.at_symbol(Symbol::Semicolon) && !parser.at_eof() {
            return Err(parser.error_expected(&["`;`", "end of input"]));
        }
    }
}

/// Parse a single expression. Handy for tests, `CHECK` constraints and REPL
/// tooling that wants to type-check a fragment.
///
/// ```
/// use basalt_sql::parse_expression;
///
/// let expr = parse_expression("a + b * 2 > 10 AND c IS NOT NULL")?;
/// assert_eq!(expr.to_string(), "a + b * 2 > 10 AND c IS NOT NULL");
/// # Ok::<(), basalt_sql::SqlError>(())
/// ```
pub fn parse_expression(sql: &str) -> ParseResult<Expr> {
    let mut parser = Parser::new(sql)?;
    let expr = parser.parse_expr()?;
    if !parser.at_eof() {
        return Err(parser.error_expected(&["end of input"]));
    }
    Ok(expr)
}

/// The parser state: the token stream and a cursor into it.
///
/// The whole input is tokenized up front rather than lexed on demand. SQL
/// statements are small, and having the full token vector available is what
/// makes the multi-token lookahead in `qualified_wildcard_ahead` and
/// `paren_starts_query` straightforward instead of requiring a
/// push-back buffer.
#[derive(Debug)]
pub struct Parser<'a> {
    source: &'a str,
    tokens: Vec<Token>,
    pos: usize,
    depth: usize,
}

impl<'a> Parser<'a> {
    /// Tokenize `sql` and position the cursor at the first token.
    pub fn new(sql: &'a str) -> ParseResult<Parser<'a>> {
        Ok(Parser {
            source: sql,
            tokens: tokenize(sql)?,
            pos: 0,
            depth: 0,
        })
    }

    // -- cursor -------------------------------------------------------------

    fn token(&self) -> &Token {
        // `tokenize` always appends `Eof` and `advance` never moves past it, so
        // the fallback is unreachable; having one at all keeps the accessor
        // total, which is worth more than an assertion that could fire.
        self.tokens.get(self.pos).unwrap_or(&EOF_TOKEN)
    }

    fn kind(&self) -> &TokenKind {
        &self.token().kind
    }

    fn kind_at(&self, offset: usize) -> Option<&TokenKind> {
        self.tokens.get(self.pos + offset).map(|t| &t.kind)
    }

    fn span(&self) -> Span {
        self.token().span
    }

    fn previous_span(&self) -> Span {
        self.tokens
            .get(self.pos.saturating_sub(1))
            .map_or_else(|| self.span(), |t| t.span)
    }

    fn advance(&mut self) -> Token {
        let token = self.token().clone();
        if self.pos < self.tokens.len().saturating_sub(1) {
            self.pos += 1;
        }
        token
    }

    fn at_eof(&self) -> bool {
        matches!(self.kind(), TokenKind::Eof)
    }

    fn at_keyword(&self, kw: Keyword) -> bool {
        matches!(self.kind(), TokenKind::Keyword(k) if *k == kw)
    }

    fn eat_keyword(&mut self, kw: Keyword) -> bool {
        let hit = self.at_keyword(kw);
        if hit {
            self.advance();
        }
        hit
    }

    /// Consume a sequence of keywords, or nothing at all if the whole sequence
    /// is not present. Needed for `IF NOT EXISTS`, `NULLS FIRST` and friends,
    /// where consuming a prefix and then failing would report the error in the
    /// wrong place.
    fn eat_keywords(&mut self, kws: &[Keyword]) -> bool {
        let matches = kws
            .iter()
            .enumerate()
            .all(|(i, kw)| matches!(self.kind_at(i), Some(TokenKind::Keyword(k)) if k == kw));
        if matches {
            for _ in kws {
                self.advance();
            }
        }
        matches
    }

    fn expect_keyword(&mut self, kw: Keyword) -> ParseResult<Span> {
        if self.at_keyword(kw) {
            Ok(self.advance().span)
        } else {
            Err(self.error_expected(&[kw.as_str()]))
        }
    }

    fn at_symbol(&self, symbol: Symbol) -> bool {
        matches!(self.kind(), TokenKind::Symbol(s) if *s == symbol)
    }

    fn eat_symbol(&mut self, symbol: Symbol) -> bool {
        let hit = self.at_symbol(symbol);
        if hit {
            self.advance();
        }
        hit
    }

    fn expect_symbol(&mut self, symbol: Symbol) -> ParseResult<Span> {
        if self.at_symbol(symbol) {
            Ok(self.advance().span)
        } else {
            let wanted = format!("`{symbol}`");
            Err(self.error_expected(&[wanted.as_str()]))
        }
    }

    /// Guard a recursive descent step against unbounded nesting.
    fn recurse<T>(&mut self, f: impl FnOnce(&mut Self) -> ParseResult<T>) -> ParseResult<T> {
        self.depth += 1;
        if self.depth > MAX_RECURSION_DEPTH {
            return Err(SqlError::new(
                self.span(),
                format!("query nests more than {MAX_RECURSION_DEPTH} levels deep"),
            )
            .with_hint("this is almost always unbalanced parentheses"));
        }
        let result = f(self);
        self.depth -= 1;
        result
    }

    // -- diagnostics --------------------------------------------------------

    /// Build the standard "expected X, found Y" error at the current token.
    fn error_expected(&self, expected: &[&str]) -> SqlError {
        let found = self.kind().describe();
        let error = SqlError::new(
            self.span(),
            format!("expected {}, found {found}", join_alternatives(expected)),
        );
        // Only guess at a misspelled keyword when a keyword was actually one of
        // the things we were looking for.
        let wanted_keyword = expected
            .iter()
            .any(|e| e.chars().all(|c| c.is_ascii_uppercase() || c == ' ') && !e.is_empty());
        if let (TokenKind::Ident(name), true) = (self.kind(), wanted_keyword) {
            if let Some(kw) = closest_keyword(name) {
                return error.with_hint(format!("did you mean `{kw}`?"));
            }
        }
        error
    }

    // -- statements ---------------------------------------------------------

    /// Parse one statement, leaving the cursor on whatever follows it.
    pub fn parse_statement(&mut self) -> ParseResult<Statement> {
        match self.kind() {
            TokenKind::Keyword(Keyword::Explain) => self.parse_explain(),
            TokenKind::Keyword(Keyword::Create) => self.parse_create(),
            TokenKind::Keyword(Keyword::Drop) => self.parse_drop(),
            TokenKind::Keyword(Keyword::Insert) => self.parse_insert(),
            TokenKind::Keyword(Keyword::Select | Keyword::With | Keyword::Values) => {
                Ok(Statement::Query(Box::new(self.parse_query()?)))
            }
            TokenKind::Symbol(Symbol::LeftParen) if self.paren_starts_query() => {
                Ok(Statement::Query(Box::new(self.parse_query()?)))
            }
            _ => Err(self.error_expected(&[
                "SELECT", "WITH", "VALUES", "INSERT", "CREATE", "DROP", "EXPLAIN",
            ])),
        }
    }

    fn parse_explain(&mut self) -> ParseResult<Statement> {
        self.expect_keyword(Keyword::Explain)?;
        let analyze = self.eat_keyword(Keyword::Analyze);
        let verbose = self.eat_keyword(Keyword::Verbose);
        let statement = self.recurse(Self::parse_statement)?;
        Ok(Statement::Explain(Explain {
            analyze,
            verbose,
            statement: Box::new(statement),
        }))
    }

    fn parse_create(&mut self) -> ParseResult<Statement> {
        self.expect_keyword(Keyword::Create)?;
        let or_replace = self.eat_keywords(&[Keyword::Or, Keyword::Replace]);
        if self.eat_keyword(Keyword::View) {
            let name = self.parse_object_name()?;
            let columns = if self.at_symbol(Symbol::LeftParen) {
                self.parse_parenthesised_idents()?
            } else {
                Vec::new()
            };
            self.expect_keyword(Keyword::As)?;
            let query = self.parse_query()?;
            return Ok(Statement::CreateView(CreateView {
                name,
                or_replace,
                columns,
                query: Box::new(query),
            }));
        }
        if or_replace {
            return Err(self
                .error_expected(&["VIEW"])
                .with_hint("`CREATE OR REPLACE` applies to views; tables use `DROP TABLE` first"));
        }
        // Naming both continuations matters: `CREATE t (...)` is a common slip,
        // and an error that says only "expected TABLE" leaves the reader
        // wondering whether views are supported at all.
        if !self.at_keyword(Keyword::Table) {
            return Err(self.error_expected(&["TABLE", "VIEW"]));
        }
        self.expect_keyword(Keyword::Table)?;
        let if_not_exists = self.eat_keywords(&[Keyword::If, Keyword::Not, Keyword::Exists]);
        let name = self.parse_object_name()?;
        if self.eat_keyword(Keyword::As) {
            let query = self.parse_query()?;
            return Ok(Statement::CreateTable(CreateTable {
                name,
                if_not_exists,
                columns: Vec::new(),
                query: Some(Box::new(query)),
            }));
        }
        self.expect_symbol(Symbol::LeftParen).map_err(|e| {
            e.with_hint("a table is created either from a column list `(a INT, ...)` or from a query with `AS SELECT ...`")
        })?;
        let mut columns = Vec::new();
        loop {
            columns.push(self.parse_column_def()?);
            if !self.eat_symbol(Symbol::Comma) {
                break;
            }
        }
        self.expect_symbol(Symbol::RightParen)?;
        Ok(Statement::CreateTable(CreateTable {
            name,
            if_not_exists,
            columns,
            query: None,
        }))
    }

    fn parse_column_def(&mut self) -> ParseResult<ColumnDef> {
        let name = self.parse_ident()?;
        let data_type = self.parse_data_type()?;
        let mut options = Vec::new();
        loop {
            if self.eat_keywords(&[Keyword::Not, Keyword::Null]) {
                options.push(ColumnOption::NotNull);
            } else if self.eat_keyword(Keyword::Null) {
                options.push(ColumnOption::Null);
            } else if self.eat_keywords(&[Keyword::Primary, Keyword::Key]) {
                options.push(ColumnOption::PrimaryKey);
            } else if self.eat_keyword(Keyword::Unique) {
                options.push(ColumnOption::Unique);
            } else if self.eat_keyword(Keyword::Default) {
                options.push(ColumnOption::Default(self.parse_expr()?));
            } else {
                return Ok(ColumnDef {
                    name,
                    data_type,
                    options,
                });
            }
        }
    }

    fn parse_drop(&mut self) -> ParseResult<Statement> {
        self.expect_keyword(Keyword::Drop)?;
        let is_view = if self.eat_keyword(Keyword::Table) {
            false
        } else if self.eat_keyword(Keyword::View) {
            true
        } else {
            return Err(self.error_expected(&["TABLE", "VIEW"]));
        };
        let if_exists = self.eat_keywords(&[Keyword::If, Keyword::Exists]);
        let mut names = vec![self.parse_object_name()?];
        while self.eat_symbol(Symbol::Comma) {
            names.push(self.parse_object_name()?);
        }
        Ok(if is_view {
            Statement::DropView(DropView { names, if_exists })
        } else {
            Statement::DropTable(DropTable { names, if_exists })
        })
    }

    fn parse_insert(&mut self) -> ParseResult<Statement> {
        self.expect_keyword(Keyword::Insert)?;
        self.expect_keyword(Keyword::Into)?;
        let table = self.parse_object_name()?;
        let columns = if self.at_symbol(Symbol::LeftParen) && !self.paren_starts_query() {
            self.parse_parenthesised_idents()?
        } else {
            Vec::new()
        };
        let source = self
            .parse_query()
            .map_err(|e| e.with_hint("the rows come from `VALUES (...)` or from a `SELECT`"))?;
        Ok(Statement::Insert(Insert {
            table,
            columns,
            source: Box::new(source),
        }))
    }

    // -- queries ------------------------------------------------------------

    /// Parse a full query: `WITH`, a set expression, then `ORDER BY`/`LIMIT`.
    pub fn parse_query(&mut self) -> ParseResult<Query> {
        self.recurse(|p| {
            let with = if p.at_keyword(Keyword::With) {
                Some(p.parse_with()?)
            } else {
                None
            };
            let body = p.parse_set_expr(0)?;
            let order_by = if p.eat_keywords(&[Keyword::Order, Keyword::By]) {
                p.parse_order_by_list()?
            } else {
                if p.at_keyword(Keyword::Order) {
                    // See the GROUP BY case: the error belongs on the token
                    // that should have been BY.
                    p.advance();
                    return Err(p
                        .error_expected(&["ORDER BY"])
                        .with_hint("the clause is spelled `ORDER BY`"));
                }
                Vec::new()
            };
            // Both orders are accepted; the printer always emits LIMIT first.
            let mut limit = None;
            let mut offset = None;
            for _ in 0..2 {
                if limit.is_none() && p.eat_keyword(Keyword::Limit) {
                    limit = Some(p.parse_expr()?);
                } else if offset.is_none() && p.eat_keyword(Keyword::Offset) {
                    offset = Some(p.parse_expr()?);
                } else {
                    break;
                }
            }
            Ok(Query {
                with,
                body,
                order_by,
                limit,
                offset,
            })
        })
    }

    fn parse_with(&mut self) -> ParseResult<With> {
        self.expect_keyword(Keyword::With)?;
        let recursive = self.eat_keyword(Keyword::Recursive);
        let mut ctes = Vec::new();
        loop {
            let name = self.parse_ident()?;
            let columns = if self.at_symbol(Symbol::LeftParen) {
                self.parse_parenthesised_idents()?
            } else {
                Vec::new()
            };
            self.expect_keyword(Keyword::As).map_err(|e| {
                e.with_hint("a common table expression is written `name AS (SELECT ...)`")
            })?;
            self.expect_symbol(Symbol::LeftParen)?;
            let query = self.parse_query()?;
            self.expect_symbol(Symbol::RightParen)?;
            ctes.push(Cte {
                name,
                columns,
                query: Box::new(query),
            });
            if !self.eat_symbol(Symbol::Comma) {
                return Ok(With { recursive, ctes });
            }
        }
    }

    /// Precedence-climbing over the set operators (`INTERSECT` binds tighter
    /// than `UNION`/`EXCEPT`, which are left-associative).
    fn parse_set_expr(&mut self, min_precedence: Precedence) -> ParseResult<SetExpr> {
        let mut left = self.parse_set_expr_primary()?;
        loop {
            let op = match self.kind() {
                TokenKind::Keyword(Keyword::Union) => SetOperator::Union,
                TokenKind::Keyword(Keyword::Except) => SetOperator::Except,
                TokenKind::Keyword(Keyword::Intersect) => SetOperator::Intersect,
                _ => return Ok(left),
            };
            if op.precedence() <= min_precedence {
                return Ok(left);
            }
            self.advance();
            let quantifier = if self.eat_keyword(Keyword::All) {
                SetQuantifier::All
            } else if self.eat_keyword(Keyword::Distinct) {
                SetQuantifier::Distinct
            } else {
                SetQuantifier::None
            };
            let right = self.recurse(|p| p.parse_set_expr(op.precedence()))?;
            left = SetExpr::SetOperation {
                op,
                quantifier,
                left: Box::new(left),
                right: Box::new(right),
            };
        }
    }

    fn parse_set_expr_primary(&mut self) -> ParseResult<SetExpr> {
        match self.kind() {
            TokenKind::Keyword(Keyword::Select) => {
                Ok(SetExpr::Select(Box::new(self.parse_select()?)))
            }
            TokenKind::Keyword(Keyword::Values) => Ok(SetExpr::Values(self.parse_values()?)),
            TokenKind::Symbol(Symbol::LeftParen) => {
                self.advance();
                let query = self.recurse(Self::parse_query)?;
                self.expect_symbol(Symbol::RightParen)?;
                Ok(SetExpr::Query(Box::new(query)))
            }
            _ => Err(self.error_expected(&["SELECT", "VALUES", "`(`"])),
        }
    }

    fn parse_values(&mut self) -> ParseResult<Values> {
        self.expect_keyword(Keyword::Values)?;
        let mut rows = Vec::new();
        loop {
            self.expect_symbol(Symbol::LeftParen)?;
            let mut row = Vec::new();
            if !self.at_symbol(Symbol::RightParen) {
                loop {
                    row.push(self.parse_expr()?);
                    if !self.eat_symbol(Symbol::Comma) {
                        break;
                    }
                }
            }
            self.expect_symbol(Symbol::RightParen)?;
            rows.push(row);
            if !self.eat_symbol(Symbol::Comma) {
                return Ok(Values { rows });
            }
        }
    }

    fn parse_select(&mut self) -> ParseResult<Select> {
        self.expect_keyword(Keyword::Select)?;
        let distinct = if self.eat_keyword(Keyword::Distinct) {
            true
        } else {
            self.eat_keyword(Keyword::All);
            false
        };
        let mut projection = vec![self.parse_select_item()?];
        while self.eat_symbol(Symbol::Comma) {
            if self.at_keyword(Keyword::From) {
                return Err(SqlError::new(
                    self.previous_span(),
                    "trailing comma in the select list",
                )
                .with_hint("remove the `,` before FROM"));
            }
            projection.push(self.parse_select_item()?);
        }
        // A bare identifier here cannot start a clause and was not taken as an
        // alias, so it is a misspelling. Naming the clauses that *could* come
        // next is what turns `SELECT * FORM t` into "did you mean `FROM`?".
        if matches!(self.kind(), TokenKind::Ident(_)) {
            return Err(self.error_expected(&[
                "FROM",
                "WHERE",
                "GROUP BY",
                "HAVING",
                "ORDER BY",
                "LIMIT",
                "end of statement",
            ]));
        }
        let from = if self.eat_keyword(Keyword::From) {
            let mut refs = vec![self.parse_table_ref()?];
            while self.eat_symbol(Symbol::Comma) {
                refs.push(self.parse_table_ref()?);
            }
            refs
        } else {
            Vec::new()
        };
        let selection = if self.eat_keyword(Keyword::Where) {
            Some(self.parse_expr()?)
        } else {
            None
        };
        let group_by = if self.eat_keywords(&[Keyword::Group, Keyword::By]) {
            let mut exprs = vec![self.parse_expr()?];
            while self.eat_symbol(Symbol::Comma) {
                exprs.push(self.parse_expr()?);
            }
            exprs
        } else {
            if self.at_keyword(Keyword::Group) {
                // Step past GROUP so the error underlines whatever was written
                // instead of BY. Pointing at GROUP would be technically true
                // and practically useless: the reader can see GROUP is fine.
                self.advance();
                return Err(self
                    .error_expected(&["GROUP BY"])
                    .with_hint("the clause is spelled `GROUP BY`"));
            }
            Vec::new()
        };
        let having = if self.eat_keyword(Keyword::Having) {
            Some(self.parse_expr()?)
        } else {
            None
        };
        Ok(Select {
            distinct,
            projection,
            from,
            selection,
            group_by,
            having,
        })
    }

    fn parse_select_item(&mut self) -> ParseResult<SelectItem> {
        if self.at_symbol(Symbol::Star) {
            return Ok(SelectItem::Wildcard(NodeSpan(self.advance().span)));
        }
        if let Some(parts) = self.qualified_wildcard_ahead() {
            let mut idents = Vec::with_capacity(parts);
            for i in 0..parts {
                if i > 0 {
                    self.expect_symbol(Symbol::Period)?;
                }
                idents.push(self.parse_ident()?);
            }
            self.expect_symbol(Symbol::Period)?;
            self.expect_symbol(Symbol::Star)?;
            return Ok(SelectItem::QualifiedWildcard(ObjectName(idents)));
        }
        let expr = self.parse_expr()?;
        let alias = self.parse_optional_alias()?;
        Ok(SelectItem::Expr { expr, alias })
    }

    /// Number of identifier parts if the tokens ahead are `a.b.*`, else `None`.
    fn qualified_wildcard_ahead(&self) -> Option<usize> {
        let mut parts = 0;
        let mut i = 0;
        loop {
            match self.kind_at(i) {
                Some(TokenKind::Ident(_)) => {}
                Some(TokenKind::Keyword(k)) if !k.is_reserved() => {}
                _ => return None,
            }
            parts += 1;
            i += 1;
            if !matches!(self.kind_at(i), Some(TokenKind::Symbol(Symbol::Period))) {
                return None;
            }
            i += 1;
            if matches!(self.kind_at(i), Some(TokenKind::Symbol(Symbol::Star))) {
                return Some(parts);
            }
        }
    }

    /// `[AS] alias` — the `AS` is optional, so an alias is only recognised when
    /// the next token could not continue the expression.
    fn parse_optional_alias(&mut self) -> ParseResult<Option<Ident>> {
        if self.eat_keyword(Keyword::As) {
            return self.parse_ident().map(Some).map_err(|e| {
                e.with_hint("`AS` must be followed by a name; quote it if it is a keyword")
            });
        }
        match self.kind() {
            TokenKind::Ident(_) => {
                self.reject_misspelled_clause()?;
                Ok(Some(self.parse_ident()?))
            }
            TokenKind::Keyword(k) if !k.is_reserved() => Ok(Some(self.parse_ident()?)),
            _ => Ok(None),
        }
    }

    /// Refuse to read a misspelled clause keyword as an alias.
    ///
    /// Because `AS` is optional, `SELECT * FROM t WERE a` parses `WERE` as the
    /// table's alias and only fails two tokens later, pointing at `a`. The
    /// error is then in the wrong place and says nothing useful. Recognising
    /// the near miss here means the diagnostic lands on the typo itself, which
    /// is the whole difference between a five-second fix and a puzzled minute.
    ///
    /// The check is deliberately narrow: only clause-introducing keywords, only
    /// an edit distance of one, and only for names long enough that a
    /// single-character difference is unlikely to be a real alias.
    fn reject_misspelled_clause(&mut self) -> ParseResult<()> {
        const CLAUSE_KEYWORDS: &[&str] = &[
            "WHERE", "GROUP", "ORDER", "HAVING", "LIMIT", "OFFSET", "UNION", "SELECT", "FROM",
        ];
        let TokenKind::Ident(name) = self.kind() else {
            return Ok(());
        };
        if name.len() < 4 {
            return Ok(());
        }
        let upper = name.to_ascii_uppercase();
        for candidate in CLAUSE_KEYWORDS {
            if upper == *candidate {
                continue;
            }
            if edit_distance_at_most_one(&upper, candidate) {
                return Err(SqlError::new(
                    self.span(),
                    format!("`{name}` is not a valid alias here"),
                )
                .with_hint(format!("did you mean `{candidate}`?")));
            }
        }
        Ok(())
    }

    fn parse_order_by_list(&mut self) -> ParseResult<Vec<OrderByExpr>> {
        let mut items = Vec::new();
        loop {
            let expr = self.parse_expr()?;
            let asc = if self.eat_keyword(Keyword::Asc) {
                Some(true)
            } else if self.eat_keyword(Keyword::Desc) {
                Some(false)
            } else {
                None
            };
            let nulls_first = if self.eat_keyword(Keyword::Nulls) {
                if self.eat_keyword(Keyword::First) {
                    Some(true)
                } else if self.eat_keyword(Keyword::Last) {
                    Some(false)
                } else {
                    return Err(self.error_expected(&["FIRST", "LAST"]));
                }
            } else {
                None
            };
            items.push(OrderByExpr {
                expr,
                asc,
                nulls_first,
            });
            if !self.eat_symbol(Symbol::Comma) {
                return Ok(items);
            }
        }
    }

    // -- FROM ---------------------------------------------------------------

    fn parse_table_ref(&mut self) -> ParseResult<TableRef> {
        let relation = self.parse_table_factor()?;
        let mut joins = Vec::new();
        loop {
            let natural = self.at_keyword(Keyword::Natural);
            let Some(operator) = self.peek_join_operator() else {
                return Ok(TableRef { relation, joins });
            };
            if natural {
                self.advance();
            }
            self.consume_join_operator(operator)?;
            let relation = self.parse_table_factor()?;
            let constraint = if natural {
                if self.at_keyword(Keyword::On) || self.at_keyword(Keyword::Using) {
                    return Err(SqlError::new(
                        self.span(),
                        "a NATURAL join cannot also have an ON or USING clause",
                    )
                    .with_hint("NATURAL already means \"join on every commonly named column\""));
                }
                JoinConstraint::Natural
            } else if self.eat_keyword(Keyword::On) {
                JoinConstraint::On(self.parse_expr()?)
            } else if self.eat_keyword(Keyword::Using) {
                JoinConstraint::Using(self.parse_parenthesised_idents()?)
            } else if operator == JoinOperator::Cross {
                JoinConstraint::None
            } else {
                return Err(self.error_expected(&["ON", "USING"]).with_hint(
                    "an inner or outer join needs a condition; use CROSS JOIN for a cartesian product",
                ));
            };
            joins.push(Join {
                relation,
                operator,
                constraint,
            });
        }
    }

    /// Look at the tokens ahead and decide which join, if any, starts here.
    fn peek_join_operator(&self) -> Option<JoinOperator> {
        let offset = usize::from(self.at_keyword(Keyword::Natural));
        match self.kind_at(offset) {
            Some(TokenKind::Keyword(Keyword::Join | Keyword::Inner)) => Some(JoinOperator::Inner),
            Some(TokenKind::Keyword(Keyword::Left)) => Some(JoinOperator::Left),
            Some(TokenKind::Keyword(Keyword::Right)) => Some(JoinOperator::Right),
            Some(TokenKind::Keyword(Keyword::Full)) => Some(JoinOperator::Full),
            Some(TokenKind::Keyword(Keyword::Cross)) => Some(JoinOperator::Cross),
            _ => None,
        }
    }

    fn consume_join_operator(&mut self, operator: JoinOperator) -> ParseResult<()> {
        match operator {
            JoinOperator::Inner => {
                self.eat_keyword(Keyword::Inner);
            }
            JoinOperator::Cross => {
                self.advance();
            }
            JoinOperator::Left | JoinOperator::Right | JoinOperator::Full => {
                self.advance();
                self.eat_keyword(Keyword::Outer);
            }
        }
        self.expect_keyword(Keyword::Join)?;
        Ok(())
    }

    fn parse_table_factor(&mut self) -> ParseResult<TableFactor> {
        self.recurse(|p| {
            if p.at_symbol(Symbol::LeftParen) {
                if p.paren_starts_query() {
                    p.advance();
                    let subquery = p.parse_query()?;
                    p.expect_symbol(Symbol::RightParen)?;
                    let alias = p.parse_table_alias()?;
                    return Ok(TableFactor::Derived {
                        subquery: Box::new(subquery),
                        alias,
                    });
                }
                p.advance();
                let inner = p.parse_table_ref()?;
                p.expect_symbol(Symbol::RightParen)?;
                return Ok(TableFactor::Nested(Box::new(inner)));
            }
            let name = p.parse_object_name().map_err(|e| {
                e.with_hint("a FROM item is a table name, a parenthesised subquery, or a join")
            })?;
            let alias = p.parse_table_alias()?;
            Ok(TableFactor::Table { name, alias })
        })
    }

    fn parse_table_alias(&mut self) -> ParseResult<Option<TableAlias>> {
        let Some(name) = self.parse_optional_alias()? else {
            return Ok(None);
        };
        let columns = if self.at_symbol(Symbol::LeftParen) {
            self.parse_parenthesised_idents()?
        } else {
            Vec::new()
        };
        Ok(Some(TableAlias { name, columns }))
    }

    /// `true` if the `(` at the cursor opens a query rather than a join tree or
    /// an expression. Skips any number of nested `(` so that `((SELECT 1))` is
    /// recognised.
    fn paren_starts_query(&self) -> bool {
        let mut i = 0;
        while matches!(self.kind_at(i), Some(TokenKind::Symbol(Symbol::LeftParen))) {
            i += 1;
        }
        matches!(
            self.kind_at(i),
            Some(TokenKind::Keyword(
                Keyword::Select | Keyword::Values | Keyword::With
            ))
        )
    }

    // -- names --------------------------------------------------------------

    fn parse_ident(&mut self) -> ParseResult<Ident> {
        match self.kind().clone() {
            TokenKind::Ident(value) => {
                let span = self.advance().span;
                Ok(Ident::new(value, span))
            }
            TokenKind::Keyword(kw) if !kw.is_reserved() => {
                let span = self.advance().span;
                Ok(Ident::new(kw.as_str().to_ascii_lowercase(), span))
            }
            TokenKind::Keyword(kw) => {
                Err(self.error_expected(&["an identifier"]).with_hint(format!(
                    "`{kw}` is a reserved word; write it as \"{}\" to use it as a name",
                    kw.as_str().to_ascii_lowercase()
                )))
            }
            _ => Err(self.error_expected(&["an identifier"])),
        }
    }

    fn parse_object_name(&mut self) -> ParseResult<ObjectName> {
        let mut parts = vec![self.parse_ident()?];
        while self.at_symbol(Symbol::Period) {
            // Do not swallow the `.` of `t.*`, which is not a name.
            if matches!(self.kind_at(1), Some(TokenKind::Symbol(Symbol::Star))) {
                break;
            }
            self.advance();
            parts.push(self.parse_ident()?);
        }
        Ok(ObjectName(parts))
    }

    fn parse_parenthesised_idents(&mut self) -> ParseResult<Vec<Ident>> {
        self.expect_symbol(Symbol::LeftParen)?;
        let mut idents = vec![self.parse_ident()?];
        while self.eat_symbol(Symbol::Comma) {
            idents.push(self.parse_ident()?);
        }
        self.expect_symbol(Symbol::RightParen)?;
        Ok(idents)
    }

    // -- types --------------------------------------------------------------

    /// Parse a SQL type name into a [`DataType`].
    ///
    /// Both the SQL-standard spellings (`BIGINT`, `VARCHAR`, `DOUBLE
    /// PRECISION`) and Basalt's own canonical names (`INT64`, `UTF8`,
    /// `FLOAT64`) are accepted, so that the output of
    /// [`DataType::Display`](std::fmt::Display) always parses back to the same
    /// type — that is what makes the printer's round trip exact.
    ///
    /// One spelling deliberately disagrees with PostgreSQL: **`INT8` is an
    /// 8-bit integer**, not an 8-byte one, because it is Basalt's own name for
    /// `Int8` and having one name mean two different widths depending on which
    /// manual you read is worse than not supporting the alias. Write `BIGINT`
    /// or `INT64` for 64-bit.
    ///
    /// `VARCHAR(n)` and `CHAR(n)` accept and **ignore** the length: Basalt
    /// strings are variable length and a declared maximum that is not enforced
    /// is a lie, so it is not recorded.
    pub fn parse_data_type(&mut self) -> ParseResult<DataType> {
        if self.at_keyword(Keyword::Null) {
            self.advance();
            return Ok(DataType::Null);
        }
        let start = self.span();
        let name = match self.kind().clone() {
            TokenKind::Ident(value) => {
                self.advance();
                value
            }
            _ => return Err(self.error_expected(&["a type name"])),
        };
        let simple = match name.as_str() {
            "boolean" | "bool" => Some(DataType::Boolean),
            "tinyint" | "int8" => Some(DataType::Int8),
            "smallint" | "int16" => Some(DataType::Int16),
            "int" | "integer" | "int32" => Some(DataType::Int32),
            "bigint" | "int64" => Some(DataType::Int64),
            "utinyint" | "uint8" => Some(DataType::UInt8),
            "usmallint" | "uint16" => Some(DataType::UInt16),
            "uinteger" | "uint32" => Some(DataType::UInt32),
            "ubigint" | "uint64" => Some(DataType::UInt64),
            "real" | "float32" => Some(DataType::Float32),
            "float64" => Some(DataType::Float64),
            "date" | "date32" => Some(DataType::Date32),
            "binary" | "blob" | "bytea" => Some(DataType::Binary),
            "text" | "string" | "utf8" => Some(DataType::Utf8),
            _ => None,
        };
        if let Some(dt) = simple {
            return Ok(dt);
        }
        match name.as_str() {
            // `FLOAT` without a precision is a double in every dialect that
            // matters; `FLOAT(n)` is not supported because the standard's
            // "binary digits of precision" rule confuses more than it helps.
            "float" => Ok(DataType::Float64),
            "double" => {
                self.eat_type_word("precision");
                Ok(DataType::Float64)
            }
            "varchar" | "char" | "character" => {
                if self.at_symbol(Symbol::LeftParen) {
                    self.parse_type_arguments()?;
                }
                Ok(DataType::Utf8)
            }
            "decimal" | "numeric" => {
                let args = if self.at_symbol(Symbol::LeftParen) {
                    self.parse_type_arguments()?
                } else {
                    Vec::new()
                };
                let (precision, scale) = match args.as_slice() {
                    [] => (DEFAULT_DECIMAL_PRECISION, DEFAULT_DECIMAL_SCALE),
                    [p] => (parse_u8(p, self, start)?, 0),
                    [p, s] => (parse_u8(p, self, start)?, parse_u8(s, self, start)?),
                    _ => {
                        return Err(SqlError::new(
                            start.to(self.previous_span()),
                            "DECIMAL takes at most two arguments",
                        )
                        .with_hint("write `DECIMAL(precision, scale)`"))
                    }
                };
                DataType::decimal128(precision, i8::try_from(scale).unwrap_or(i8::MAX)).ok_or_else(
                    || {
                        SqlError::new(
                            start.to(self.previous_span()),
                            format!("DECIMAL({precision}, {scale}) is not a valid type"),
                        )
                        .with_hint("precision must be 1..=38 and scale must be 0..=precision")
                    },
                )
            }
            "timestamp" => {
                let args = if self.at_symbol(Symbol::LeftParen) {
                    self.parse_type_arguments()?
                } else {
                    Vec::new()
                };
                let unit = match args.as_slice() {
                    [] => TimeUnit::Microsecond,
                    [u] => time_unit(u).ok_or_else(|| {
                        SqlError::new(
                            start.to(self.previous_span()),
                            format!("`{u}` is not a timestamp resolution"),
                        )
                        .with_hint("write one of `s`, `ms`, `us`, `ns` or 0, 3, 6, 9")
                    })?,
                    _ => {
                        return Err(SqlError::new(
                            start.to(self.previous_span()),
                            "TIMESTAMP takes at most one argument",
                        ))
                    }
                };
                Ok(DataType::Timestamp(unit))
            }
            _ => Err(SqlError::new(start, format!("unknown type name `{name}`"))
                .with_optional_hint(
                    did_you_mean(&name, TYPE_NAMES.iter().copied())
                        .map(|s| format!("did you mean `{}`?", s.to_ascii_uppercase())),
                )),
        }
    }

    /// Consume `(a, b)` after a type name, returning the raw argument words.
    fn parse_type_arguments(&mut self) -> ParseResult<Vec<String>> {
        self.expect_symbol(Symbol::LeftParen)?;
        let mut args = Vec::new();
        loop {
            match self.kind().clone() {
                TokenKind::Number(text) => {
                    self.advance();
                    args.push(text);
                }
                TokenKind::Ident(word) => {
                    self.advance();
                    args.push(word);
                }
                _ => return Err(self.error_expected(&["a number", "a resolution such as `us`"])),
            }
            if !self.eat_symbol(Symbol::Comma) {
                break;
            }
        }
        self.expect_symbol(Symbol::RightParen)?;
        Ok(args)
    }

    fn eat_type_word(&mut self, word: &str) -> bool {
        if matches!(self.kind(), TokenKind::Ident(v) if v == word) {
            self.advance();
            true
        } else {
            false
        }
    }

    // -- expressions --------------------------------------------------------

    /// Parse a complete expression.
    pub fn parse_expr(&mut self) -> ParseResult<Expr> {
        self.parse_subexpr(0)
    }

    /// The Pratt loop: parse a prefix expression, then keep folding in infix
    /// operators whose precedence is **strictly greater** than
    /// `min_precedence`. Passing an operator's own precedence when parsing its
    /// right operand is what makes it left-associative.
    pub fn parse_subexpr(&mut self, min_precedence: Precedence) -> ParseResult<Expr> {
        self.recurse(|p| {
            let mut left = p.parse_prefix()?;
            while let Some(precedence) = p.peek_infix_precedence() {
                if precedence <= min_precedence {
                    break;
                }
                left = p.parse_infix(left, precedence)?;
            }
            Ok(left)
        })
    }

    /// Precedence of the infix operator at the cursor, if there is one.
    fn peek_infix_precedence(&self) -> Option<Precedence> {
        match self.kind() {
            TokenKind::Symbol(s) => symbol_binary_operator(*s).map(BinaryOperator::precedence),
            TokenKind::Keyword(Keyword::And) => Some(PREC_AND),
            TokenKind::Keyword(Keyword::Or) => Some(PREC_OR),
            TokenKind::Keyword(
                Keyword::Is | Keyword::In | Keyword::Between | Keyword::Like | Keyword::Ilike,
            ) => Some(PREC_COMPARISON),
            // `NOT` is infix only in `NOT IN` / `NOT BETWEEN` / `NOT LIKE`;
            // everywhere else it is the prefix operator.
            TokenKind::Keyword(Keyword::Not) => matches!(
                self.kind_at(1),
                Some(TokenKind::Keyword(
                    Keyword::In | Keyword::Between | Keyword::Like | Keyword::Ilike
                ))
            )
            .then_some(PREC_COMPARISON),
            _ => None,
        }
    }

    fn parse_infix(&mut self, left: Expr, precedence: Precedence) -> ParseResult<Expr> {
        let start = left.span;
        if let TokenKind::Symbol(symbol) = self.kind() {
            if let Some(op) = symbol_binary_operator(*symbol) {
                self.advance();
                let right = self.parse_subexpr(precedence)?;
                let span = start.to(right.span);
                return Ok(Expr::new(
                    ExprKind::BinaryOp {
                        left: Box::new(left),
                        op,
                        right: Box::new(right),
                    },
                    span,
                ));
            }
        }
        if self.eat_keyword(Keyword::And) {
            let right = self.parse_subexpr(PREC_AND)?;
            let span = start.to(right.span);
            return Ok(Expr::new(
                ExprKind::BinaryOp {
                    left: Box::new(left),
                    op: BinaryOperator::And,
                    right: Box::new(right),
                },
                span,
            ));
        }
        if self.eat_keyword(Keyword::Or) {
            let right = self.parse_subexpr(PREC_OR)?;
            let span = start.to(right.span);
            return Ok(Expr::new(
                ExprKind::BinaryOp {
                    left: Box::new(left),
                    op: BinaryOperator::Or,
                    right: Box::new(right),
                },
                span,
            ));
        }
        if self.eat_keyword(Keyword::Is) {
            let negated = self.eat_keyword(Keyword::Not);
            if self.eat_keyword(Keyword::Null) {
                let span = start.to(self.previous_span());
                return Ok(Expr::new(
                    ExprKind::IsNull {
                        expr: Box::new(left),
                        negated,
                    },
                    span,
                ));
            }
            if self.eat_keyword(Keyword::Distinct) {
                self.expect_keyword(Keyword::From)?;
                let right = self.parse_subexpr(PREC_COMPARISON)?;
                let span = start.to(right.span);
                return Ok(Expr::new(
                    ExprKind::IsDistinctFrom {
                        left: Box::new(left),
                        right: Box::new(right),
                        negated,
                    },
                    span,
                ));
            }
            return Err(self
                .error_expected(&["NULL", "DISTINCT FROM"])
                .with_hint("`IS TRUE` is not supported; compare with `= TRUE` instead"));
        }
        let negated = self.eat_keyword(Keyword::Not);
        if self.eat_keyword(Keyword::In) {
            return self.parse_in(left, negated);
        }
        if self.eat_keyword(Keyword::Between) {
            let low = self.parse_subexpr(PREC_COMPARISON)?;
            self.expect_keyword(Keyword::And)
                .map_err(|e| e.with_hint("`BETWEEN` needs two bounds: `x BETWEEN low AND high`"))?;
            let high = self.parse_subexpr(PREC_COMPARISON)?;
            let span = start.to(high.span);
            return Ok(Expr::new(
                ExprKind::Between {
                    expr: Box::new(left),
                    low: Box::new(low),
                    high: Box::new(high),
                    negated,
                },
                span,
            ));
        }
        let case_insensitive = if self.eat_keyword(Keyword::Like) {
            false
        } else if self.eat_keyword(Keyword::Ilike) {
            true
        } else {
            return Err(self.error_expected(&["IN", "BETWEEN", "LIKE", "ILIKE"]));
        };
        let pattern = self.parse_subexpr(PREC_COMPARISON)?;
        let escape = if self.eat_keyword(Keyword::Escape) {
            Some(Box::new(self.parse_subexpr(PREC_COMPARISON)?))
        } else {
            None
        };
        let span = start.to(self.previous_span());
        Ok(Expr::new(
            ExprKind::Like {
                expr: Box::new(left),
                pattern: Box::new(pattern),
                escape,
                negated,
                case_insensitive,
            },
            span,
        ))
    }

    fn parse_in(&mut self, left: Expr, negated: bool) -> ParseResult<Expr> {
        let start = left.span;
        if self.paren_starts_query() {
            self.expect_symbol(Symbol::LeftParen)?;
            let subquery = self.parse_query()?;
            let end = self.expect_symbol(Symbol::RightParen)?;
            return Ok(Expr::new(
                ExprKind::InSubquery {
                    expr: Box::new(left),
                    subquery: Box::new(subquery),
                    negated,
                },
                start.to(end),
            ));
        }
        self.expect_symbol(Symbol::LeftParen).map_err(|e| {
            e.with_hint("`IN` takes a parenthesised list or subquery: `x IN (1, 2)`")
        })?;
        let mut list = Vec::new();
        if !self.at_symbol(Symbol::RightParen) {
            loop {
                list.push(self.parse_expr()?);
                if !self.eat_symbol(Symbol::Comma) {
                    break;
                }
            }
        }
        let end = self.expect_symbol(Symbol::RightParen)?;
        Ok(Expr::new(
            ExprKind::InList {
                expr: Box::new(left),
                list,
                negated,
            },
            start.to(end),
        ))
    }

    fn parse_prefix(&mut self) -> ParseResult<Expr> {
        let start = self.span();
        match self.kind().clone() {
            TokenKind::Number(text) => {
                self.advance();
                Ok(Expr::new(ExprKind::Literal(Literal::Number(text)), start))
            }
            TokenKind::String(text) => {
                self.advance();
                Ok(Expr::new(ExprKind::Literal(Literal::String(text)), start))
            }
            TokenKind::Parameter(param) => {
                self.advance();
                Ok(Expr::new(ExprKind::Parameter(param), start))
            }
            TokenKind::Keyword(Keyword::Null) => {
                self.advance();
                Ok(Expr::new(ExprKind::Literal(Literal::Null), start))
            }
            TokenKind::Keyword(Keyword::True) => {
                self.advance();
                Ok(Expr::new(ExprKind::Literal(Literal::Boolean(true)), start))
            }
            TokenKind::Keyword(Keyword::False) => {
                self.advance();
                Ok(Expr::new(ExprKind::Literal(Literal::Boolean(false)), start))
            }
            TokenKind::Keyword(Keyword::Not) => {
                self.advance();
                let expr = self.parse_subexpr(PREC_NOT)?;
                let span = start.to(expr.span);
                Ok(Expr::new(
                    ExprKind::UnaryOp {
                        op: UnaryOperator::Not,
                        expr: Box::new(expr),
                    },
                    span,
                ))
            }
            TokenKind::Symbol(s @ (Symbol::Minus | Symbol::Plus)) => {
                self.advance();
                let op = if s == Symbol::Minus {
                    UnaryOperator::Minus
                } else {
                    UnaryOperator::Plus
                };
                let expr = self.parse_subexpr(PREC_UNARY)?;
                let span = start.to(expr.span);
                Ok(Expr::new(
                    ExprKind::UnaryOp {
                        op,
                        expr: Box::new(expr),
                    },
                    span,
                ))
            }
            TokenKind::Keyword(Keyword::Case) => self.parse_case(),
            TokenKind::Keyword(Keyword::Cast) => self.parse_cast(),
            TokenKind::Keyword(Keyword::Extract) => self.parse_extract(),
            TokenKind::Keyword(Keyword::Exists) => {
                self.advance();
                self.parse_exists(start, false)
            }
            TokenKind::Symbol(Symbol::LeftParen) => {
                if self.paren_starts_query() {
                    self.advance();
                    let query = self.parse_query()?;
                    let end = self.expect_symbol(Symbol::RightParen)?;
                    return Ok(Expr::new(
                        ExprKind::Subquery(Box::new(query)),
                        start.to(end),
                    ));
                }
                self.advance();
                let inner = self.parse_expr()?;
                let end = self.expect_symbol(Symbol::RightParen)?;
                // Parentheses are not represented in the tree; only the span
                // grows, so that an error about the whole group underlines it.
                Ok(Expr::new(inner.kind, start.to(end)))
            }
            TokenKind::Symbol(Symbol::Star) => {
                Err(SqlError::new(start, "`*` is not an expression")
                    .with_hint("write `*` on its own in the select list, or `count(*)`"))
            }
            TokenKind::Ident(_) => self.parse_ident_expr(),
            TokenKind::Keyword(kw) if !kw.is_reserved() => self.parse_ident_expr(),
            TokenKind::Keyword(kw) => {
                Err(self.error_expected(&["an expression"]).with_hint(format!(
                    "`{kw}` is a reserved word and cannot start an expression; \
                     quote it as \"{}\" to use it as a name",
                    kw.as_str().to_ascii_lowercase()
                )))
            }
            _ => Err(self.error_expected(&["an expression"])),
        }
    }

    /// An identifier in expression position: a column reference, or a function
    /// call if it is followed by `(`.
    fn parse_ident_expr(&mut self) -> ParseResult<Expr> {
        let name = self.parse_object_name()?;
        let start = name.span();
        if !self.at_symbol(Symbol::LeftParen) {
            return Ok(Expr::new(ExprKind::Column(name), start));
        }
        self.advance();
        let distinct = self.eat_keyword(Keyword::Distinct);
        let mut args = Vec::new();
        if !self.at_symbol(Symbol::RightParen) {
            loop {
                if self.at_symbol(Symbol::Star) {
                    args.push(FunctionArg::Wildcard(NodeSpan(self.advance().span)));
                } else {
                    args.push(FunctionArg::Expr(self.parse_expr()?));
                }
                if !self.eat_symbol(Symbol::Comma) {
                    break;
                }
            }
        }
        let mut end = self.expect_symbol(Symbol::RightParen)?;
        let over = if self.eat_keyword(Keyword::Over) {
            let spec = self.parse_window_spec()?;
            end = self.previous_span();
            Some(spec)
        } else {
            None
        };
        Ok(Expr::new(
            ExprKind::Function(Function {
                name,
                args,
                distinct,
                over,
            }),
            start.to(end),
        ))
    }

    fn parse_window_spec(&mut self) -> ParseResult<WindowSpec> {
        self.expect_symbol(Symbol::LeftParen).map_err(|e| {
            e.with_hint("`OVER` takes a window specification: `OVER (PARTITION BY .. ORDER BY ..)`")
        })?;
        let partition_by = if self.eat_keywords(&[Keyword::Partition, Keyword::By]) {
            let mut exprs = vec![self.parse_expr()?];
            while self.eat_symbol(Symbol::Comma) {
                exprs.push(self.parse_expr()?);
            }
            exprs
        } else {
            Vec::new()
        };
        let order_by = if self.eat_keywords(&[Keyword::Order, Keyword::By]) {
            self.parse_order_by_list()?
        } else {
            Vec::new()
        };
        let frame = if self.at_keyword(Keyword::Rows) || self.at_keyword(Keyword::Range) {
            Some(self.parse_window_frame()?)
        } else {
            None
        };
        self.expect_symbol(Symbol::RightParen)?;
        Ok(WindowSpec {
            partition_by,
            order_by,
            frame,
        })
    }

    fn parse_window_frame(&mut self) -> ParseResult<WindowFrame> {
        let units = if self.eat_keyword(Keyword::Rows) {
            WindowFrameUnits::Rows
        } else {
            self.expect_keyword(Keyword::Range)?;
            WindowFrameUnits::Range
        };
        if self.eat_keyword(Keyword::Between) {
            let start = self.parse_window_frame_bound()?;
            self.expect_keyword(Keyword::And)?;
            let end = self.parse_window_frame_bound()?;
            return Ok(WindowFrame {
                units,
                start,
                end: Some(end),
            });
        }
        let start = self.parse_window_frame_bound()?;
        Ok(WindowFrame {
            units,
            start,
            end: None,
        })
    }

    fn parse_window_frame_bound(&mut self) -> ParseResult<WindowFrameBound> {
        if self.eat_keyword(Keyword::Unbounded) {
            return if self.eat_keyword(Keyword::Preceding) {
                Ok(WindowFrameBound::UnboundedPreceding)
            } else if self.eat_keyword(Keyword::Following) {
                Ok(WindowFrameBound::UnboundedFollowing)
            } else {
                Err(self.error_expected(&["PRECEDING", "FOLLOWING"]))
            };
        }
        if self.eat_keywords(&[Keyword::Current, Keyword::Row]) {
            return Ok(WindowFrameBound::CurrentRow);
        }
        let offset = self.parse_subexpr(PREC_COMPARISON)?;
        if self.eat_keyword(Keyword::Preceding) {
            Ok(WindowFrameBound::Preceding(Box::new(offset)))
        } else if self.eat_keyword(Keyword::Following) {
            Ok(WindowFrameBound::Following(Box::new(offset)))
        } else {
            Err(self.error_expected(&["PRECEDING", "FOLLOWING"]))
        }
    }

    fn parse_case(&mut self) -> ParseResult<Expr> {
        let start = self.expect_keyword(Keyword::Case)?;
        let operand = if self.at_keyword(Keyword::When) {
            None
        } else if self.at_keyword(Keyword::End) {
            // Catch the empty CASE here rather than letting `parse_expr` fail
            // on `END`, which would say "expected an expression" and point at
            // the wrong problem.
            return Err(self
                .error_expected(&["WHEN"])
                .with_hint("a CASE needs at least one `WHEN ... THEN ...` arm"));
        } else {
            Some(Box::new(self.parse_expr()?))
        };
        let mut arms = Vec::new();
        while self.eat_keyword(Keyword::When) {
            let condition = self.parse_expr()?;
            self.expect_keyword(Keyword::Then)?;
            let result = self.parse_expr()?;
            arms.push(CaseArm { condition, result });
        }
        if arms.is_empty() {
            return Err(self
                .error_expected(&["WHEN"])
                .with_hint("a CASE needs at least one `WHEN ... THEN ...` arm"));
        }
        let else_result = if self.eat_keyword(Keyword::Else) {
            Some(Box::new(self.parse_expr()?))
        } else {
            None
        };
        let end = self
            .expect_keyword(Keyword::End)
            .map_err(|e| e.with_hint("every CASE is terminated by `END`"))?;
        Ok(Expr::new(
            ExprKind::Case {
                operand,
                arms,
                else_result,
            },
            start.to(end),
        ))
    }

    fn parse_cast(&mut self) -> ParseResult<Expr> {
        let start = self.expect_keyword(Keyword::Cast)?;
        self.expect_symbol(Symbol::LeftParen)?;
        let expr = self.parse_expr()?;
        self.expect_keyword(Keyword::As)
            .map_err(|e| e.with_hint("the syntax is `CAST(expr AS type)`"))?;
        let data_type = self.parse_data_type()?;
        let end = self.expect_symbol(Symbol::RightParen)?;
        Ok(Expr::new(
            ExprKind::Cast {
                expr: Box::new(expr),
                data_type,
            },
            start.to(end),
        ))
    }

    fn parse_extract(&mut self) -> ParseResult<Expr> {
        let start = self.expect_keyword(Keyword::Extract)?;
        self.expect_symbol(Symbol::LeftParen)?;
        let field_span = self.span();
        let word = match self.kind().clone() {
            TokenKind::Ident(value) => value,
            TokenKind::String(value) => value,
            _ => return Err(self.error_expected(&["a date field such as YEAR"])),
        };
        self.advance();
        let field = DateTimeField::from_uppercase(&word.to_ascii_uppercase()).ok_or_else(|| {
            SqlError::new(field_span, format!("`{word}` is not a date or time field"))
                .with_optional_hint(
                    did_you_mean(&word, DateTimeField::ALL.iter().map(|f| f.as_str()))
                        .map(|s| format!("did you mean `{s}`?")),
                )
        })?;
        self.expect_keyword(Keyword::From)
            .map_err(|e| e.with_hint("the syntax is `EXTRACT(YEAR FROM ts)`"))?;
        let expr = self.parse_expr()?;
        let end = self.expect_symbol(Symbol::RightParen)?;
        Ok(Expr::new(
            ExprKind::Extract {
                field,
                expr: Box::new(expr),
            },
            start.to(end),
        ))
    }

    fn parse_exists(&mut self, start: Span, negated: bool) -> ParseResult<Expr> {
        self.expect_symbol(Symbol::LeftParen)
            .map_err(|e| e.with_hint("`EXISTS` takes a subquery: `EXISTS (SELECT 1 FROM ...)`"))?;
        let query = self.parse_query()?;
        let end = self.expect_symbol(Symbol::RightParen)?;
        Ok(Expr::new(
            ExprKind::Exists {
                subquery: Box::new(query),
                negated,
            },
            start.to(end),
        ))
    }

    /// The source text this parser was built from, for rendering diagnostics.
    pub fn source(&self) -> &'a str {
        self.source
    }
}

