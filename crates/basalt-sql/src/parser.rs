fn parse_u8(text: &str, parser: &Parser<'_>, span: Span) -> ParseResult<u8> {
    text.parse::<u8>().map_err(|_| {
        SqlError::new(
            span.to(parser.previous_span()),
            format!("`{text}` is not a valid precision or scale"),
        )
        .with_hint("precision must be 1..=38 and scale must be 0..=precision")
    })
}

fn time_unit(word: &str) -> Option<TimeUnit> {
    Some(match word {
        "s" | "0" => TimeUnit::Second,
        "ms" | "3" => TimeUnit::Millisecond,
        "us" | "6" => TimeUnit::Microsecond,
        "ns" | "9" => TimeUnit::Nanosecond,
        _ => return None,
    })
}

fn symbol_binary_operator(symbol: Symbol) -> Option<BinaryOperator> {
    Some(match symbol {
        Symbol::Eq => BinaryOperator::Eq,
        Symbol::NotEq => BinaryOperator::NotEq,
        Symbol::Lt => BinaryOperator::Lt,
        Symbol::LtEq => BinaryOperator::LtEq,
        Symbol::Gt => BinaryOperator::Gt,
        Symbol::GtEq => BinaryOperator::GtEq,
        Symbol::Concat => BinaryOperator::Concat,
        Symbol::Plus => BinaryOperator::Plus,
        Symbol::Minus => BinaryOperator::Minus,
        Symbol::Star => BinaryOperator::Multiply,
        Symbol::Slash => BinaryOperator::Divide,
        Symbol::Percent => BinaryOperator::Modulo,
        _ => return None,
    })
}

/// Whether two equal-ish strings differ by at most one edit.
///
/// A bounded check rather than a full edit distance: the answer is only ever
/// compared against one, so computing the exact distance would be wasted work,
/// and the early exits make the common "not close at all" case a length test.
fn edit_distance_at_most_one(a: &str, b: &str) -> bool {
    let (a, b): (&[u8], &[u8]) = (a.as_bytes(), b.as_bytes());
    let (long, short) = if a.len() >= b.len() { (a, b) } else { (b, a) };
    if long.len() - short.len() > 1 {
        return false;
    }
    let mut i = 0;
    let mut j = 0;
    let mut edited = false;
    while i < long.len() && j < short.len() {
        if long[i] == short[j] {
            i += 1;
            j += 1;
            continue;
        }
        if edited {
            return false;
        }
        edited = true;
        if long.len() == short.len() {
            i += 1;
            j += 1;
        } else {
            i += 1;
        }
    }
    true
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used)]

    use super::*;

    fn expr(sql: &str) -> Expr {
        parse_expression(sql).unwrap_or_else(|e| panic!("{sql}: {e}"))
    }

    fn expr_err(sql: &str) -> SqlError {
        parse_expression(sql).unwrap_err()
    }

    #[test]
    fn precedence_is_standard_sql() {
        assert_eq!(expr("a + b * c").to_string(), "a + b * c");
        assert_eq!(expr("(a + b) * c").to_string(), "(a + b) * c");
        assert_eq!(expr("a OR b AND c").to_string(), "a OR b AND c");
        assert_eq!(expr("(a OR b) AND c").to_string(), "(a OR b) AND c");
        // NOT binds looser than comparison.
        assert_eq!(expr("NOT a = b").to_string(), "NOT a = b");
        assert_eq!(expr("NOT a = b").kind, expr("NOT (a = b)").kind);
        // || binds tighter than comparison, looser than +.
        assert_eq!(expr("a || b = c").kind, expr("(a || b) = c").kind);
        assert_eq!(expr("a || b + c").kind, expr("a || (b + c)").kind);
        // Unary minus binds tightest.
        assert_eq!(expr("-a + b").kind, expr("(-a) + b").kind);
        assert_eq!(expr("-a * b").kind, expr("(-a) * b").kind);
    }

    #[test]
    fn arithmetic_is_left_associative() {
        assert_eq!(expr("a - b - c").kind, expr("(a - b) - c").kind);
        assert_ne!(expr("a - b - c").kind, expr("a - (b - c)").kind);
        assert_eq!(expr("a / b / c").kind, expr("(a / b) / c").kind);
    }

    #[test]
    fn between_does_not_swallow_the_outer_and() {
        let e = expr("a BETWEEN 1 AND 2 AND b");
        assert_eq!(e.to_string(), "a BETWEEN 1 AND 2 AND b");
        let ExprKind::BinaryOp { op, .. } = &e.kind else {
            panic!("expected the top node to be AND, got {:?}", e.kind);
        };
        assert_eq!(*op, BinaryOperator::And);
    }

    #[test]
    fn the_comparison_family() {
        assert_eq!(expr("a IS NULL").to_string(), "a IS NULL");
        assert_eq!(expr("a IS NOT NULL").to_string(), "a IS NOT NULL");
        assert_eq!(
            expr("a IS DISTINCT FROM b").to_string(),
            "a IS DISTINCT FROM b"
        );
        assert_eq!(
            expr("a IS NOT DISTINCT FROM b").to_string(),
            "a IS NOT DISTINCT FROM b"
        );
        assert_eq!(expr("a NOT IN (1, 2)").to_string(), "a NOT IN (1, 2)");
        assert_eq!(
            expr("a NOT BETWEEN 1 AND 2").to_string(),
            "a NOT BETWEEN 1 AND 2"
        );
        assert_eq!(
            expr("a NOT LIKE '%x%' ESCAPE '\\'").to_string(),
            "a NOT LIKE '%x%' ESCAPE '\\'"
        );
        assert_eq!(expr("a ILIKE 'x'").to_string(), "a ILIKE 'x'");
    }

    #[test]
    fn spans_point_at_the_offending_text() {
        let e = expr_err("a + ");
        assert_eq!(e.span(), Span::at(4));
        assert!(e.message().contains("expected an expression"), "{e}");

        let e = expr_err("f(a,)");
        assert!(e.message().contains("expected an expression"), "{e}");
        assert_eq!(e.span(), Span::new(4, 5));
    }

    #[test]
    fn helpful_hints() {
        let e = parse("SELECT * FORM t").unwrap_err();
        assert_eq!(e.hint(), Some("did you mean `FROM`?"));

        let e = parse("SELECT a, FROM t").unwrap_err();
        assert!(e.message().contains("trailing comma"), "{e}");

        let e = parse("SELECT * FROM a JOIN b").unwrap_err();
        assert!(e.hint().unwrap().contains("CROSS JOIN"), "{e}");

        let e = expr_err("CASE END");
        assert!(e.hint().unwrap().contains("WHEN"), "{e}");

        let e = expr_err("CAST(a int)");
        assert!(e.hint().unwrap().contains("CAST(expr AS type)"), "{e}");

        let e = expr_err("a IS TRUE");
        assert!(e.hint().unwrap().contains("= TRUE"), "{e}");

        let e = parse("SELECT * FROM t GROUP a").unwrap_err();
        assert!(e.hint().unwrap().contains("GROUP BY"), "{e}");

        let e = parse("SELECT select FROM t").unwrap_err();
        assert!(e.hint().unwrap().contains("reserved word"), "{e}");
    }

    #[test]
    fn nesting_is_bounded() {
        let deep = format!("SELECT {}1{}", "(".repeat(500), ")".repeat(500));
        let e = parse(&deep).unwrap_err();
        assert!(e.message().contains("nests more than"), "{e}");
    }

    #[test]
    fn types_accept_both_spellings() {
        for (sql, expected) in [
            ("CAST(a AS BIGINT)", DataType::Int64),
            ("CAST(a AS INT64)", DataType::Int64),
            ("CAST(a AS int)", DataType::Int32),
            ("CAST(a AS DOUBLE PRECISION)", DataType::Float64),
            ("CAST(a AS FLOAT64)", DataType::Float64),
            ("CAST(a AS VARCHAR(10))", DataType::Utf8),
            ("CAST(a AS UTF8)", DataType::Utf8),
            ("CAST(a AS DECIMAL(10, 2))", DataType::Decimal128(10, 2)),
            ("CAST(a AS DECIMAL)", DataType::Decimal128(38, 10)),
            (
                "CAST(a AS TIMESTAMP)",
                DataType::Timestamp(TimeUnit::Microsecond),
            ),
            (
                "CAST(a AS TIMESTAMP(ns))",
                DataType::Timestamp(TimeUnit::Nanosecond),
            ),
            (
                "CAST(a AS TIMESTAMP(3))",
                DataType::Timestamp(TimeUnit::Millisecond),
            ),
            ("CAST(a AS NULL)", DataType::Null),
        ] {
            let ExprKind::Cast { data_type, .. } = expr(sql).kind else {
                panic!("{sql} did not parse as a cast");
            };
            assert_eq!(data_type, expected, "{sql}");
        }
        let e = expr_err("CAST(a AS varchr)");
        assert!(e.message().contains("unknown type name"), "{e}");
        assert!(e.hint().unwrap().contains("VARCHAR"), "{e}");
        let e = expr_err("CAST(a AS DECIMAL(99))");
        assert!(e.message().contains("not a valid type"), "{e}");
    }

    #[test]
    fn parse_rejects_two_statements() {
        let e = parse("SELECT 1 SELECT 2").unwrap_err();
        assert!(e.message().contains("expected end of statement"), "{e}");
        assert_eq!(parse_many("SELECT 1; SELECT 2").unwrap().len(), 2);
        assert_eq!(parse_many(";;").unwrap().len(), 0);
        assert_eq!(parse_many("").unwrap().len(), 0);
    }

    #[test]
    fn source_is_available_for_rendering() {
        let parser = Parser::new("SELECT 1").unwrap();
        assert_eq!(parser.source(), "SELECT 1");
    }
}
