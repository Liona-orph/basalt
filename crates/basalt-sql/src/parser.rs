//! A recursive-descent parser with a Pratt expression parser.
//!
//! # Shape
//!
//! Statements, clauses and the `FROM` tree are parsed by ordinary
//! recursive-descent functions, one per grammar production, each named after it.
//! Expressions are parsed by [`Parser::parse_subexpr`], a precedence-climbing
//! (Pratt) loop driven by the table documented on
//! [`Precedence`]. A hand-written parser is used rather
//! than a generated one for a specific reason: the error messages *are* the
//! product, and a generated parser can only ever say "unexpected token".
//!
//! # Error philosophy
//!
//! Every failure reports three things: what was expected, what was found, and —
//! when the fix is unambiguous — what to do about it. A misspelled keyword is
//! matched against the keyword table by edit distance, an unaliased derived
//! table is told to add an alias, `::` is told to use `CAST`. Where the fix is
//! *not* obvious no hint is offered, because a confident wrong suggestion costs
//! more than silence.
//!
//! # Recursion
//!
//! The parser is recursive, so its stack depth is bounded by the input's nesting
//! depth. `((((...` would therefore be a stack overflow — an abort, not an
//! error. [`MAX_RECURSION_DEPTH`] turns it into a diagnostic instead, which is
//! what makes the "random bytes never panic" test meaningful.

// Grammar productions are long by nature: `parse_select` is one linear pass
// over eight clauses and splitting it would only scatter the context.
#![allow(clippy::too_many_lines)]

